CREATE TABLE app_user (
    id UUID PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL
);

CREATE TABLE conversation (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id UUID NOT NULL,
    role VARCHAR(255) NOT NULL,
    text TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE profile_field (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    field_key VARCHAR(255) NOT NULL,
    field_value VARCHAR(500) NOT NULL,
    source VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_profile_field_user_key UNIQUE (user_id, field_key)
);

CREATE TABLE property (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL UNIQUE,
    listing_url VARCHAR(500),
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE property_value (
    property_id UUID NOT NULL,
    value_key VARCHAR(255) NOT NULL,
    value_text VARCHAR(500) NOT NULL,
    source VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    PRIMARY KEY (property_id, value_key)
);

CREATE TABLE mortgage_application (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL,
    snapshot_json TEXT NOT NULL,
    bank_ids_json TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE email_thread (
    id UUID PRIMARY KEY,
    application_id UUID NOT NULL,
    user_id UUID NOT NULL,
    bank_id VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    unread BOOLEAN NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE email (
    id UUID PRIMARY KEY,
    thread_id UUID NOT NULL,
    email_from VARCHAR(255) NOT NULL,
    type VARCHAR(255) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    body TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
